with open('views.py', 'a') as f:
    f.write('\n\n')
    f.write("# Live Chat\n")
    f.write("@require_POST\n@staff_required\ndef livechat_claim(request, pk):\n")
    f.write("    session = get_object_or_404(ChatSession, pk=pk)\n")
    f.write("    session.assigned_to = request.user\n")
    f.write("    session.status = 'active'\n")
    f.write("    session.is_escalated = True\n")
    f.write("    session.save(update_fields=['assigned_to', 'status', 'is_escalated', 'updated_at', 'last_activity_at'])\n")
    f.write("    messages.success(request, 'Chat claimed.')\n")
    f.write("    return redirect('cars:livechat_session_detail', pk=session.pk)\n\n")
    f.write("@require_POST\n@staff_required\ndef livechat_reply(request, pk):\n")
    f.write("    session = get_object_or_404(ChatSession, pk=pk)\n")
    f.write("    payload = _read_json(request) if request.content_type == 'application/json' else None\n")
    f.write("    text = (payload.get('message') if payload else request.POST.get('message')) or ''\n")
    f.write("    text = text.strip()[:1000]\n")
    f.write("    if not text:\n")
    f.write("        if payload:\n")
    f.write("            return JsonResponse({'error': 'Empty'}, status=400)\n")
    f.write("        messages.error(request, 'Message required')\n")
    f.write("        return redirect('cars:livechat_session_detail', pk=session.pk)\n")
    f.write("    ChatMessage.objects.create(session=session, sender='staff', sender_user=request.user, text=text, is_read=False)\n")
    f.write("    session.assigned_to = session.assigned_to or request.user\n")
    f.write("    session.status = 'active'\n")
    f.write("    session.save(update_fields=['assigned_to', 'status', 'last_activity_at', 'updated_at'])\n")
    f.write("    if payload:\n")
    f.write("        return JsonResponse({'ok': True})\n")
    f.write("    messages.success(request, 'Reply sent.')\n")
    f.write("    return redirect('cars:livechat_session_detail', pk=session.pk)\n\n")
    f.write("@require_POST\n@staff_required\ndef livechat_close(request, pk):\n")
    f.write("    session = get_object_or_404(ChatSession, pk=pk)\n")
    f.write("    session.status = 'closed'\n")
    f.write("    session.save(update_fields=['status', 'updated_at', 'last_activity_at'])\n")
    f.write("    messages.success(request, 'Chat closed.')\n")
    f.write("    return redirect('cars:livechat_inbox')\n\n")
    f.write("class LiveChatInboxView(StaffRequiredMixin, ListView):\n")
    f.write("    model = ChatSession\n")
    f.write("    template_name = 'cars/livechat_inbox.html'\n")
    f.write("    context_object_name = 'sessions'\n")
    f.write("    paginate_by = 30\n")
    f.write("    def get_queryset(self):\n")
    f.write("        return ChatSession.objects.exclude(status='closed').order_by('-last_activity_at')\n\n")
    f.write("class LiveChatSessionDetailView(StaffRequiredMixin, DetailView):\n")
    f.write("    model = ChatSession\n")
    f.write("    template_name = 'cars/livechat_session_detail.html'\n")
    f.write("    context_object_name = 'chat_session'\n")
    f.write("    def get_queryset(self):\n")
    f.write("        return ChatSession.objects.prefetch_related('messages')\n")
    f.write("    def get(self, request, *args, **kwargs):\n")
    f.write("        response = super().get(request, *args, **kwargs)\n")
    f.write("        ChatMessage.objects.filter(session=self.object, sender='user', is_read=False).update(is_read=True)\n")
    f.write("        return response\n")
print('done')
