# Public entry point
# ---------------------------------------------------------------------------

def get_reply(text, user=None):
    """Return the chatbot's structured answer to ``text``.

    The returned dict has: ``reply`` (str), ``suggestions`` (list[str]),
    ``links`` (list[{label, url}]), ``intent`` (str) and ``escalate`` (bool).
    """
    text = (text or '').strip()[:MAX_MESSAGE_LENGTH]

    rule = _rule_reply(text)
    result = {
        'reply': rule.get('reply', ''),
        'suggestions': list(rule.get('suggestions', SUGGESTIONS)),
        'links': rule.get('links', []),
        'intent': rule.get('intent', 'unknown'),
        'escalate': rule.get('escalate', False),
    }

    llm = _llm_reply(text, rule)
    if llm:
        result['reply'] = llm
        result['escalate'] = False
        if result['intent'] == 'unknown':
            result['intent'] = 'llm'

    return result
