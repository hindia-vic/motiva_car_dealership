"""The site chatbot's answer engine.

Out of the box it answers common dealership questions with a small, offline
keyword/intent engine that reads live site data (contact details, dealership
name, and available inventory). No third-party service, API key, or network
access is required.

If ``CHATBOT_PROVIDER`` and ``CHATBOT_API_KEY`` are configured, answers are
generated by an LLM grounded in the same knowledge base instead. Any error,
timeout, or missing configuration silently falls back to the built-in rules, so
the widget never breaks because a provider is down.
"""

import json
import logging
import re
import urllib.request

from django.conf import settings
from django.db.models import Q
from django.urls import reverse

from .money import format_money

logger = logging.getLogger(__name__)

#: Longest visitor message we will accept/consider.
MAX_MESSAGE_LENGTH = 500

#: Quick-reply chips shown in the widget.
SUGGESTIONS = [
    "Do you offer financing?",
    "What are your hours?",
    "Do you have any SUVs?",
    "How do I book a test drive?",
    "Do you take trade-ins?",
]

_BODY_TYPES = [
    'sedan', 'suv', 'truck', 'hatchback', 'coupe', 'convertible',
    'van', 'minivan', 'wagon', 'crossover',
]

#: Words that should never be treated as a make/model search term.
_STOPWORDS = {
    'the', 'and', 'you', 'your', 'any', 'have', 'has', 'got', 'do', 'does',
    'car', 'cars', 'vehicle', 'vehicles', 'looking', 'look', 'for', 'want',
    'need', 'about', 'with', 'that', 'this', 'are', 'can', 'could', 'would',
    'please', 'hello', 'hey', 'there', 'much', 'many', 'price', 'cost',
    'available', 'stock', 'inventory', 'what', 'which', 'where', 'when',
    'how', 'who', 'why', 'is', 'of', 'to', 'a', 'an', 'me', 'my', 'i',
}

# ---------------------------------------------------------------------------
# Intent patterns (checked in priority order)
# ---------------------------------------------------------------------------

_PATTERNS = [
    ('greeting', re.compile(
        r'\b(hi|hello|hey|howdy|good\s+(morning|afternoon|evening))\b', re.I)),
    ('thanks', re.compile(
        r'\b(thanks|thank\s+you|thx|cheers|appreciate)\b', re.I)),
    ('goodbye', re.compile(
        r"\b(bye|goodbye|see\s+you|that'?s\s+all|no\s+thanks)\b", re.I)),
    ('hours', re.compile(
        r'\b(hours?|open|opening|close|closing|closed|weekend|sunday|saturday)\b',
        re.I)),
    ('location', re.compile(
        r'\b(where|location|address|direction|directions|located|visit|map|'
        r'find\s+you|showroom)\b', re.I)),
    ('contact', re.compile(
        r'\b(contact|phone|call|email|whatsapp|reach|number|talk\s+to)\b', re.I)),
    ('financing', re.compile(
        r'\b(financ\w*|loan|lease|credit|payment|monthly|down\s?payment|apr|'
        r'interest|afford)\b', re.I)),
    ('trade_in', re.compile(
        r'\b(trade[\s-]?in|trade|apprais\w*|sell\s+my|my\s+(old\s+)?car)\b',
        re.I)),
    ('test_drive', re.compile(
        r'\b(test[\s-]?drive|book|appointment|schedule|reserve\s+a\s+time)\b',
        re.I)),
    ('reviews', re.compile(
        r'\b(review|reviews|testimonial\w*|rating|feedback|reputation|'
        r'trustworthy)\b', re.I)),
    ('about', re.compile(
        r'\b(about|who\s+are\s+you|company|your\s+team|mission|vision)\b', re.I)),
    ('pricing', re.compile(
        r'\b(price|pricing|cost|how\s+much|expensive|cheap|deal)\b', re.I)),
    ('order', re.compile(
        r'\b(order|buy|purchase|checkout|how\s+do\s+i\s+get|reserve)\b', re.I)),
    ('inventory', re.compile(
        r'\b(inventory|stock|available|in\s+stock|do\s+you\s+have|cars?|'
        r'vehicles?|looking\s+for|sedan|suv|truck|hatchback|coupe|convertible|'
        r'van|minivan|wagon|crossover|electric|hybrid|diesel)\b', re.I)),
]


def _link(label, url_name, *args):
    """Build a {label, url} link, or None if it can't be reversed."""
    try:
        return {'label': label, 'url': reverse(url_name, args=args)}
    except Exception:  # pragma: no cover - reverse should always succeed
        return None


def _links(*items):
    return [link for link in items if link]


def _contact_info():
    from .models import ContactInfo
    try:
        return ContactInfo.get_solo()
    except Exception:
        return None


def _brand_name():
    from .models import DealershipInfo
    try:
        return DealershipInfo.display_name()
    except Exception:
        return 'Car Dealership'


# ---------------------------------------------------------------------------
# Inventory search
# ---------------------------------------------------------------------------

def _inventory_reply(text):
    """Answer a question about what vehicles are available."""
    from .models import Car

    lowered = text.lower()
    available = Car.objects.filter(status='available')
    queryset = available

    # Narrow by body type when the visitor mentions one.
    body_label = None
    for body in _BODY_TYPES:
        if re.search(r'\b' + re.escape(body) + r's?\b', lowered):
            queryset = queryset.filter(body_type__icontains=body)
            body_label = body
            break

    # Narrow by make/model using meaningful tokens that actually match stock.
    tokens = [
        token for token in re.findall(r'[a-z0-9]+', lowered)
        if len(token) > 2 and token not in _STOPWORDS
    ]
    if tokens:
        match = Q()
        for token in tokens:
            match |= Q(make__icontains=token) | Q(model__icontains=token)
        narrowed = queryset.filter(match)
        if narrowed.exists():
            queryset = narrowed

    total = queryset.count()
    cars = list(queryset.order_by('-year')[:3])

    if total == 0:
        reply = (
            "I couldn't find a matching vehicle in stock right now. Our "
            "inventory changes often, so it's worth checking back — you can "
            "browse everything we have on the Browse Cars page."
        )
        return {
            'reply': reply,
            'links': _links(_link('Browse cars', 'cars:browse_cars')),
        }

    if cars:
        lines = [f"Yes — we currently have {total} matching "
                 f"{'vehicle' if total == 1 else 'vehicles'}:"]
        for car in cars:
            price = format_money(car.asking_price) if car.asking_price else 'Call for price'
            lines.append(f"• {car.year} {car.make} {car.model} — {price}")
        if total > len(cars):
            lines.append(f"…and {total - len(cars)} more.")
        reply = "\n".join(lines)
    else:  # pragma: no cover - defensive
        reply = "Here's what we have in stock."

    return {
        'reply': reply,
        'links': _links(
            _link('Browse all cars', 'cars:browse_cars'),
            _link('View', 'cars:car_detail', cars[0].id) if cars else None,
        ),
    }


