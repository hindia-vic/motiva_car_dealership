def _knowledge_context():
    """A compact, public snapshot of site facts for the LLM system prompt."""
    from .models import Car

    lines = [f"Dealership name: {_brand_name()}"]
    info = _contact_info()
    if info:
        lines.append(f"Address: {info.address}")
        lines.append(f"Phone: {info.phone}")
        lines.append(f"Email: {info.email}")
        lines.append(f"Hours: {info.hours}")
    try:
        available = Car.objects.filter(status='available')
        lines.append(f"Available vehicles: {available.count()}")
        for car in available.order_by('-year')[:15]:
            price = format_money(car.asking_price) if car.asking_price else "call for price"
            lines.append(f"- {car.year} {car.make} {car.model} ({price})")
    except Exception:  # pragma: no cover - defensive
        pass
    return "\n".join(lines)


_SYSTEM_PROMPT = (
    "You are a friendly, concise assistant for {brand}. Answer the visitor's "
    "question in one to three short sentences. Use only the facts below; if you "
    "don't know, say so and suggest the visitor use the Contact page to reach "
    "the team. Never invent prices, availability, or policies.\n\n"
    "Site facts:\n{context}\n{hint}"
)


def _post_json(url, payload, headers):
    data = json.dumps(payload).encode('utf-8')
    request = urllib.request.Request(url, data=data, headers=headers)
    with urllib.request.urlopen(request, timeout=getattr(settings, 'CHATBOT_TIMEOUT', 15)) as response:
        return json.loads(response.read().decode('utf-8'))


def _llm_reply(text, rule=None):
    """Ask the configured LLM provider for an answer, or return None.

    Returns None when the chatbot has no provider configured (the default) and
    on any error, so the caller can fall back to the built-in rules.

    ``rule`` is the built-in engine's result. When it matched a known topic its
    answer is passed to the model as an authoritative hint, so the LLM adds
    natural phrasing and extra help without contradicting the site's own facts.
    """
    provider = (getattr(settings, 'CHATBOT_PROVIDER', '') or '').lower()
    api_key = getattr(settings, 'CHATBOT_API_KEY', '')
    model = getattr(settings, 'CHATBOT_MODEL', '')
    if not provider or not api_key:
        return None

    hint = ''
    if rule and rule.get('intent') not in (None, 'unknown') and rule.get('reply'):
        hint = (
            "Known FAQ answer for this question (treat as correct; you may "
            "rephrase it more naturally but must not contradict it or add "
            "facts that aren't listed above):\n" + rule['reply']
        )

    system = _SYSTEM_PROMPT.format(
        brand=_brand_name(), context=_knowledge_context(), hint=hint
    )
    try:
        if provider in ('openai', 'openai_compatible'):
            base = getattr(settings, 'CHATBOT_BASE_URL', '') or 'https://api.openai.com/v1'
            url = base.rstrip('/') + '/chat/completions'
            payload = {
                'model': model or 'gpt-4o-mini',
                'messages': [
                    {'role': 'system', 'content': system},
                    {'role': 'user', 'content': text},
                ],
                'max_tokens': 300,
                'temperature': 0.2,
            }
            data = _post_json(url, payload, {
                'Content-Type': 'application/json',
                'Authorization': f'Bearer {api_key}',
            })
            return (data['choices'][0]['message']['content'] or '').strip() or None

        if provider == 'gemini':
            model = model or 'gemini-2.5-flash'
            url = (
                'https://generativelanguage.googleapis.com/v1beta/models/'
                f'{model}:generateContent?key={api_key}'
            )
            payload = {
                'system_instruction': {'parts': [{'text': system}]},
                'contents': [{'parts': [{'text': text}]}],
                'generationConfig': {'maxOutputTokens': 300, 'temperature': 0.2},
            }
            data = _post_json(url, payload, {'Content-Type': 'application/json'})
            return (data['candidates'][0]['content']['parts'][0]['text'] or '').strip() or None

        if provider == 'anthropic':
            url = 'https://api.anthropic.com/v1/messages'
            payload = {
                'model': model or 'claude-3-5-haiku-latest',
                'max_tokens': 300,
                'system': system,
                'messages': [{'role': 'user', 'content': text}],
            }
            data = _post_json(url, payload, {
                'Content-Type': 'application/json',
                'x-api-key': api_key,
                'anthropic-version': '2023-06-01',
            })
            return (data['content'][0]['text'] or '').strip() or None

        logger.warning('Chatbot: unknown provider %r', provider)
        return None
    except Exception:
        logger.warning('Chatbot: LLM request failed; using built-in rules', exc_info=True)
        return None


