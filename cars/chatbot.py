# Rule engine
# ---------------------------------------------------------------------------

def _detect_intent(text):
    """Return the first matching intent name for ``text`` (or ``'unknown'``)."""
    lowered = text.lower()
    for intent, pattern in _PATTERNS:
        if pattern.search(lowered):
            return intent
    return 'unknown'


def _rule_reply(text):
    """Return the built-in keyword-based answer for ``text``.

    Delegates to :func:`_rule_reply_raw`, then guarantees every result carries
    an ``intent`` and ``escalate`` flag so callers can rely on them.
    """
    result = dict(_rule_reply_raw(text))
    result.setdefault('intent', _detect_intent(text))
    result.setdefault('escalate', False)
    return result


def _rule_reply_raw(text):
    """Return the built-in keyword-based answer for ``text``."""
    lowered = text.lower()

    matched = None
    for intent, pattern in _PATTERNS:
        if pattern.search(lowered):
            matched = intent
            break

    if matched == 'greeting':
        return {
            'reply': (
                f"Hi! I'm the {_brand_name()} assistant. I can help with "
                "financing, test drives, trade-ins, our hours and location, or "
                "what's in stock. What would you like to know?"
            ),
            'links': [],
            'intent': 'greeting',
            'escalate': False,
        }

    if matched == 'thanks':
        return {
            'reply': "You're very welcome! Anything else I can help with?",
            'links': [],
            'intent': 'thanks',
            'escalate': False,
        }

    if matched == 'goodbye':
        return {
            'reply': "Thanks for stopping by — come back any time!",
            'links': _links(_link('Browse cars', 'cars:browse_cars')),
            'suggestions': [],
            'intent': 'goodbye',
            'escalate': False,
        }

    if matched == 'hours':
        info = _contact_info()
        hours = info.hours if info else 'Please contact us for our current hours.'
        return {
            'reply': f"Our showroom hours are:\n{hours}",
            'links': _links(_link('Contact us', 'cars:contact')),
        }

    if matched == 'location':
        info = _contact_info()
        address = info.address if info else 'Please contact us for directions.'
        return {
            'reply': f"You'll find us at:\n{address}\n\nWe'd love to see you!",
            'links': _links(
                _link('Contact & map', 'cars:contact'),
                _link('Book a test drive', 'cars:browse_cars'),
            ),
        }

    if matched == 'contact':
        info = _contact_info()
        details = []
        if info:
            details.append(f"Phone: {info.phone}")
            details.append(f"Email: {info.email}")
        reply = "Here's how to reach us:\n" + "\n".join(details) if details \
            else "You can reach us through the Contact page."
        return {
            'reply': reply,
            'links': _links(_link('Contact page', 'cars:contact')),
        }

    if matched == 'financing':
        return {
            'reply': (
                "Yes — we offer auto loans, leases, and financing for "
                "first-time buyers. You can estimate a monthly payment with the "
                "calculator on any vehicle page, then talk to us about options."
            ),
            'links': _links(
                _link('Financing options', 'cars:financing'),
                _link('Browse cars', 'cars:browse_cars'),
            ),
        }

    if matched == 'trade_in':
        return {
            'reply': (
                "Absolutely. We offer free appraisals and apply your trade-in "
                "value toward your purchase. Get an instant estimate of what "
                "your car is worth on our trade-in page, and we'll confirm the "
                "final number once we've seen the vehicle."
            ),
            'links': _links(
                _link('Trade-in value estimator', 'cars:trade_in'),
                _link('Contact us', 'cars:contact'),
            ),
        }

    if matched == 'test_drive':
        return {
            'reply': (
                "It's easy: open any vehicle's page and click \"Book a Test "
                "Drive\". Pick a date and time and we'll confirm your "
                "appointment by email."
            ),
            'links': _links(_link('Browse cars', 'cars:browse_cars')),
        }

    if matched == 'reviews':
        return {
            'reply': (
                "You can read what our customers say — and leave your own "
                "review — on our Reviews page."
            ),
            'links': _links(_link('Customer reviews', 'cars:reviews')),
        }

    if matched == 'about':
        return {
            'reply': (
                f"{_brand_name()} is a full-service dealership. You can read "
                "about our story, values, and team on the About page."
            ),
            'links': _links(_link('About us', 'cars:about')),
        }

    if matched == 'order':
        return {
            'reply': (
                "To buy a vehicle, open its page and click \"Place Order\" — "
                "we'll confirm by email and guide you through the next steps, "
                "including financing and trade-in."
            ),
            'links': _links(
                _link('Browse cars', 'cars:browse_cars'),
                _link('Financing options', 'cars:financing'),
            ),
        }

    if matched == 'inventory':
        result = _inventory_reply(text)
        result['intent'] = 'inventory'
        result.setdefault('escalate', False)
        return result

    if matched == 'pricing':
        result = _inventory_reply(text)
        result['intent'] = 'pricing'
        result['reply'] = (
            "Every vehicle page lists its price, and the financing calculator "
            "shows estimated monthly payments. Here's some of what we have:\n\n"
            + result['reply']
        )
        result.setdefault('escalate', False)
        return result

    # Nothing matched: be honest and offer to hand off to a person.
    return {
        'reply': (
            "I'm not sure I have an answer for that one. I can help with "
            "financing, trade-ins, test drives, hours, location, and our "
            "inventory — or I can pass your question to a member of our team."
        ),
        'links': _links(_link('Contact us', 'cars:contact')),
        'intent': 'unknown',
        'escalate': True,
    }


