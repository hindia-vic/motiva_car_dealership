with open('views.py', 'a') as f:
    f.write('\n\n')
    f.write("# Service bookings\n")
    f.write("class ServiceBookingCreateView(CreateView):\n")
    f.write("    model = ServiceRecord\n")
    f.write("    template_name = 'cars/service_booking.html'\n")
    f.write("    fields = ['service_type', 'service_date', 'description', 'customer_name', 'customer_email', 'customer_phone']\n")
    f.write("    success_url = '/service-booking/thank-you/'\n\n")
    f.write("    def form_valid(self, form):\n")
    f.write("        obj = form.save(commit=False)\n")
    f.write("        if self.request.user.is_authenticated:\n")
    f.write("            obj.user = self.request.user\n")
    f.write("            if not obj.customer_name:\n")
    f.write("                obj.customer_name = self.request.user.get_full_name() or self.request.user.username\n")
    f.write("            if not obj.customer_email:\n")
    f.write("                obj.customer_email = self.request.user.email\n")
    f.write("        obj.status = 'scheduled'\n")
    f.write("        obj.save()\n")
    f.write("        return super().form_valid(form)\n\n")
    f.write("def service_booking_thank_you(request):\n")
    f.write("    return render(request, 'cars/service_booking_thank_you.html')\n\n")
    f.write("class MyServiceBookingsView(LoginRequiredMixin, ListView):\n")
    f.write("    model = ServiceRecord\n")
    f.write("    template_name = 'cars/my_service_bookings.html'\n")
    f.write("    context_object_name = 'bookings'\n")
    f.write("    def get_queryset(self):\n")
    f.write("        return ServiceRecord.objects.filter(user=self.request.user).order_by('-service_date')\n\n")
    f.write("class ServiceBookingListView(StaffRequiredMixin, ListView):\n")
    f.write("    model = ServiceRecord\n")
    f.write("    template_name = 'cars/service_bookings_list.html'\n")
    f.write("    context_object_name = 'bookings'\n")
    f.write("    paginate_by = 20\n")
    f.write("    def get_queryset(self):\n")
    f.write("        return ServiceRecord.objects.all().order_by('-service_date')\n\n")
    f.write("class ServiceBookingDetailView(StaffRequiredMixin, DetailView):\n")
    f.write("    model = ServiceRecord\n")
    f.write("    template_name = 'cars/service_booking_detail.html'\n")
    f.write("    context_object_name = 'booking'\n\n")
    f.write("@require_POST\n@staff_required\ndef service_booking_status(request, pk):\n")
    f.write("    booking = get_object_or_404(ServiceRecord, pk=pk)\n")
    f.write("    status = request.POST.get('status')\n")
    f.write("    valid = [c[0] for c in ServiceRecord.STATUS_CHOICES]\n")
    f.write("    if status in valid:\n")
    f.write("        booking.status = status\n")
    f.write("        booking.save(update_fields=['status', 'updated_at'])\n")
    f.write("        messages.success(request, 'Service booking status updated.')\n")
    f.write("    return redirect('cars:service_booking_detail', pk=booking.pk)\n")
print('done')
