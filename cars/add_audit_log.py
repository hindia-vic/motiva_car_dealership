with open('views.py', 'a') as f:
    f.write('\n\n')
    f.write("# Audit Log\n")
    f.write("class AuditLogView(StaffRequiredMixin, TemplateView):\n")
    f.write("    template_name = 'cars/audit_log.html'\n")
    f.write("    def get_context_data(self, **kwargs):\n")
    f.write("        ctx = super().get_context_data(**kwargs)\n")
    f.write("        try:\n")
    f.write("            from cars.models import HistoricalCar, HistoricalHireBooking\n")
    f.write("            ctx['car_history'] = HistoricalCar.objects.all().order_by('-history_date')[:50]\n")
    f.write("            ctx['hire_history'] = HistoricalHireBooking.objects.all().order_by('-history_date')[:50]\n")
    f.write("        except Exception:\n")
    f.write("            pass\n")
    f.write("        return ctx\n")
print('done')
