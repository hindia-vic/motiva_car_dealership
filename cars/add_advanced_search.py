with open('views.py', 'a') as f:
    f.write('\n\n')
    f.write("# Advanced Search\n")
    f.write("class AdvancedSearchView(ListView):\n")
    f.write("    model = Car\n")
    f.write("    template_name = 'cars/advanced_search.html'\n")
    f.write("    context_object_name = 'cars'\n")
    f.write("    paginate_by = 12\n")
    f.write("    def get_queryset(self):\n")
    f.write("        qs = Car.objects.filter(status='available').select_related()\n")
    f.write("        q = self.request.GET.get('q')\n")
    f.write("        make = self.request.GET.get('make')\n")
    f.write("        model_name = self.request.GET.get('model')\n")
    f.write("        body_type = self.request.GET.get('body_type')\n")
    f.write("        fuel_type = self.request.GET.get('fuel_type')\n")
    f.write("        transmission = self.request.GET.get('transmission')\n")
    f.write("        min_price = self.request.GET.get('min_price')\n")
    f.write("        max_price = self.request.GET.get('max_price')\n")
    f.write("        min_year = self.request.GET.get('min_year')\n")
    f.write("        max_year = self.request.GET.get('max_year')\n")
    f.write("        min_mileage = self.request.GET.get('min_mileage')\n")
    f.write("        max_mileage = self.request.GET.get('max_mileage')\n")
    f.write("        branch = self.request.GET.get('branch')\n")
    f.write("        if q:\n")
    f.write("            qs = qs.filter(Q(make__icontains=q) | Q(model__icontains=q) | Q(description__icontains=q) | Q(color__icontains=q))\n")
    f.write("        if make: qs = qs.filter(make__iexact=make)\n")
    f.write("        if model_name: qs = qs.filter(model__icontains=model_name)\n")
    f.write("        if body_type: qs = qs.filter(body_type=body_type)\n")
    f.write("        if fuel_type: qs = qs.filter(fuel_type=fuel_type)\n")
    f.write("        if transmission: qs = qs.filter(transmission=transmission)\n")
    f.write("        if branch: qs = qs.filter(branch_id=branch)\n")
    f.write("        if min_price:\n")
    f.write("            try: qs = qs.filter(asking_price__gte=min_price)\n")
    f.write("            except: pass\n")
    f.write("        if max_price:\n")
    f.write("            try: qs = qs.filter(asking_price__lte=max_price)\n")
    f.write("            except: pass\n")
    f.write("        if min_year:\n")
    f.write("            try: qs = qs.filter(year__gte=min_year)\n")
    f.write("            except: pass\n")
    f.write("        if max_year:\n")
    f.write("            try: qs = qs.filter(year__lte=max_year)\n")
    f.write("            except: pass\n")
    f.write("        if min_mileage:\n")
    f.write("            try: qs = qs.filter(mileage__gte=min_mileage)\n")
    f.write("            except: pass\n")
    f.write("        if max_mileage:\n")
    f.write("            try: qs = qs.filter(mileage__lte=max_mileage)\n")
    f.write("            except: pass\n")
    f.write("        return qs.order_by('-created_at')\n")
    f.write("    def get_context_data(self, **kwargs):\n")
    f.write("        ctx = super().get_context_data(**kwargs)\n")
    f.write("        ctx['makes'] = Car.objects.filter(status='available').values_list('make', flat=True).distinct().order_by('make')\n")
    f.write("        ctx['branches'] = Branch.objects.all()\n")
    f.write("        return ctx\n")
print('done')
