with open('views.py', 'a') as f:
    f.write('\n\n')
    f.write("# Analytics Dashboard\n")
    f.write("from django.db.models import Count, Sum, Avg\n")
    f.write("from django.utils import timezone\n")
    f.write("from datetime import timedelta\n\n")
    f.write("class AnalyticsDashboardView(StaffRequiredMixin, TemplateView):\n")
    f.write("    template_name = 'cars/analytics_dashboard.html'\n")
    f.write("    def get_context_data(self, **kwargs):\n")
    f.write("        ctx = super().get_context_data(**kwargs)\n")
    f.write("        today = timezone.now().date()\n")
    f.write("        thirty_days_ago = today - timedelta(days=30)\n")
    f.write("        ctx['total_cars'] = Car.objects.count()\n")
    f.write("        ctx['available_cars'] = Car.objects.filter(status='available').count()\n")
    f.write("        ctx['sold_cars'] = Car.objects.filter(status='sold').count()\n")
    f.write("        ctx['total_inquiries'] = Inquiry.objects.count()\n")
    f.write("        ctx['recent_inquiries'] = Inquiry.objects.filter(created_at__date__gte=thirty_days_ago).count()\n")
    f.write("        ctx['total_sales'] = SalesTransaction.objects.count()\n")
    f.write("        ctx['recent_sales'] = SalesTransaction.objects.filter(sale_date__gte=thirty_days_ago).count()\n")
    f.write("        ctx['revenue_total'] = SalesTransaction.objects.aggregate(total=Sum('total_amount'))['total'] or 0\n")
    f.write("        ctx['revenue_30d'] = SalesTransaction.objects.filter(sale_date__gte=thirty_days_ago).aggregate(total=Sum('total_amount'))['total'] or 0\n")
    f.write("        ctx['hire_bookings'] = HireBooking.objects.count()\n")
    f.write("        ctx['service_bookings'] = ServiceRecord.objects.count()\n")
    f.write("        ctx['top_makes'] = Car.objects.filter(status='available').values('make').annotate(count=Count('id')).order_by('-count')[:5]\n")
    f.write("        ctx['recent_sales_list'] = SalesTransaction.objects.order_by('-sale_date')[:10]\n")
    f.write("        ctx['recent_inquiries_list'] = Inquiry.objects.order_by('-created_at')[:10]\n")
    f.write("        # Monthly sales data for chart\n")
    f.write("        months = []\n")
    f.write("        for i in range(6):\n")
    f.write("            month_start = (today.replace(day=1) - timedelta(days=30*i)).replace(day=1)\n")
    f.write("            month_end = (month_start + timedelta(days=32)).replace(day=1) - timedelta(days=1)\n")
    f.write("            count = SalesTransaction.objects.filter(sale_date__gte=month_start, sale_date__lte=month_end).count()\n")
    f.write("            months.append({'month': month_start.strftime('%b'), 'count': count})\n")
    f.write("        ctx['monthly_sales'] = list(reversed(months))\n")
    f.write("        return ctx\n")
print('done')
