with open('views.py', 'a') as f:
    f.write('\n\n')
    f.write("# Saved Searches\n")
    f.write("@login_required\n")
    f.write("def save_search(request):\n")
    f.write("    if request.method == 'POST':\n")
    f.write("        data = request.POST\n")
    f.write("        SavedSearch.objects.create(\n")
    f.write("            user=request.user,\n")
    f.write("            email=request.user.email,\n")
    f.write("            make=data.get('make',''),\n")
    f.write("            model=data.get('model',''),\n")
    f.write("            body_type=data.get('body_type',''),\n")
    f.write("            fuel_type=data.get('fuel_type',''),\n")
    f.write("            transmission=data.get('transmission',''),\n")
    f.write("        )\n")
    f.write("        messages.success(request, 'Search saved successfully.')\n")
    f.write("    return redirect(request.META.get('HTTP_REFERER','cars:advanced_search'))\n\n")
    f.write("class MySavedSearchesView(LoginRequiredMixin, ListView):\n")
    f.write("    model = SavedSearch\n")
    f.write("    template_name = 'cars/my_saved_searches.html'\n")
    f.write("    context_object_name = 'searches'\n")
    f.write("    def get_queryset(self):\n")
    f.write("        return SavedSearch.objects.filter(user=self.request.user).order_by('-created_at')\n\n")
    f.write("@login_required\n")
    f.write("def delete_saved_search(request, pk):\n")
    f.write("    search = get_object_or_404(SavedSearch, pk=pk, user=request.user)\n")
    f.write("    search.delete()\n")
    f.write("    messages.success(request, 'Saved search deleted.')\n")
    f.write("    return redirect('cars:my_saved_searches')\n")
print('done')
