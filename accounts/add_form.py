with open('forms.py', 'a') as f:
    f.write('\n\nclass CustomerDocumentForm(forms.ModelForm):\n')
    f.write('    from .models import CustomerDocument\n\n')
    f.write('    class Meta:\n')
    f.write("        model = CustomerDocument\n")
    f.write("        fields = ('document_type', 'title', 'document', 'notes')\n\n")
    f.write('    def __init__(self, *args, **kwargs):\n')
    f.write('        super().__init__(*args, **kwargs)\n')
    f.write('        for field in self.fields.values():\n')
    f.write("            if hasattr(field.widget, 'attrs'):\n")
    f.write("                field.widget.attrs['class'] = 'form-control'\n")
    f.write("        if 'document_type' in self.fields:\n")
    f.write("            self.fields['document_type'].widget.attrs['class'] = 'form-select'\n")
print('done')
